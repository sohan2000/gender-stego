def create_video_writer(video_cap, output_filename):
  """
  Create video writer function. Output video details (fps, frame width/height) must match input video.

  :param video_cap:       input video cap to obtain video details
  :param output_filename: name of output video

  :return:                video writer object
  :return:                frame width
  :return:                frame height
  :return:                fps
  :return:                bitrate
  """


  # grab the width, height, and fps of the frames in the video stream.
  frame_width = int(video_cap.get(cv2.CAP_PROP_FRAME_WIDTH))
  frame_height = int(video_cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
  fps = video_cap.get(cv2.CAP_PROP_FPS)
  bitrate = video_cap.get(cv2.CAP_PROP_BITRATE)

  # initialize the FourCC and a video writer object
  fourcc = cv2.VideoWriter_fourcc(*'MP4V')
  writer = cv2.VideoWriter(output_filename, fourcc, fps,
                            (frame_width, frame_height))

  return writer, frame_width, frame_height, fps, bitrate

# function used primarily for background generation.
# used to generate mask to feed to cleanup.pictures API to generate clean background

def blackout(img, results):
  """
  Mask genertion function. primarily used for background generation
  used to generate mask to feed to cleanup.pictures API to generate clean background
  all detected bounding boxes from YOLO detection results are whiteouted and copied into a black mask

  :param img:      frame being processed
  :param results:  YOLO model detection results

  :return:         blackout mask image
  """

  # Create a black mask of the same size as the image
  mask = np.zeros_like(img)

  # For each result (detected person)
  # create white areas based on YOLO result bounding boxes
  for result in results:
      for box in result.boxes:
          x1, y1 = int(box.xyxy[0][0]), int(box.xyxy[0][1])
          x2, y2 = int(box.xyxy[0][2]), int(box.xyxy[0][3])

          # generated bounding box from YOLO is often too small for good inpainting
          # expand the bounds by 10px or to image bounds
          height, width = img.shape[:2]

          x1 = max(0, x1-10)

          # replace bounding box with white
          mask[max(0, y1-10):min(height, y2+10), max(0, x1-10):min(width, x2+10)] = 255

  return mask

# function to generate median (dirty) background
def median_background(cap):
  """
  function to generate still(dirty) background using median background technique

  background image currently takes all frames into account

  does not return anything. instead writes dirty background to local storage

  :param cap:  input video capture object

  """

  num_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

  frames_list = []

  # add all frames to list
  for i in range(num_frames):
      success, img = cap.read()

      if not success:
          break

      # add frame to list
      frames_list.append(img)

  # reshape to 4D array (frame_count, height, width, channels)
  # and compute median for each pixel
  frames_arr = np.array(frames_list)
  med_bg = np.median(frames_arr, axis=0).astype(dtype=np.uint8)

  cv2.imwrite('bg_dirty.jpg', med_bg)

  cap.release()

