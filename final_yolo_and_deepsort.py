def predict_gender(gender_modules, track_id, crop_jpg):
  """
  gender prediction function. This function is called whenever deepSORT tracker encounters
  a new id.

  :param gender_modules:  gender detection model modules
  :param track_id:        id of new tracked object. only used for the print statement
  :param crop_jpg:        crop image containing the person to input into the gender detection model

  :return:                predicted gender. 1 for man, 0 for woman

  """

  # unpack gender modules
  gender_processor, gender_model = gender_modules

  # crop_jpg is a PIL
  gender_input = gender_processor(crop_jpg, return_tensors="pt")

  with torch.no_grad():
    logits = gender_model(**gender_input).logits

  predicted_label = logits.argmax(-1).item()

  # add new id and assigned gender to id_dict
  print(f'id: {track_id} predicted as {"man" if predicted_label == 1 else "woman" if predicted_label == 0 else None}')

  return predicted_label

