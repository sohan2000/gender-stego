def detect_people(yolo_model, img, classes=None, conf=0.5, iou=0.7, imgsz=640, augment=False):
  """
  YOLO model person detection function

  :param yolo_model: The YOLO model used for detection
  :param img:        The image/frame being processed
  :param classes:    list of ids YOLO will detect. 0 is the id for person
  :param conf:       confidence threshold for YOLO detection
  :param iou:        Intersection Over Union threshold for YOLO detection
  :param imgsz:      image size for YOLO detection (height, width)
  :param augment:    test time augmentation (TTA) for YOLO detection

  :return:           YOLO model results
  """

  if classes:
    results = yolo_model.predict(img, classes=classes, conf=conf, iou=iou, imgsz=imgsz, augment=augment, stream=True, verbose=False)
  else:
    results = yolo_model.predict(img, conf=conf, iou=iou, imgsz=imgsz, augment=augment, stream=True, verbose=False)

  return results

def add_results_to_tracker(results, DS_results, conf):
  """
  deepSORT tracker update helper function. Takes all YOLO detection results per frame
  and adds it to a list to feed to deepSORT tracker.

  :param results:     YOLO model detection results
  :param DS_results:  list that holds bounding box information for YOLO detections
  :param conf:        confidence threshold from YOLO detection
  """

  for result in results:
    for box in result.boxes:

      # bounding box around each detected person
      box_bounds = (int(box.xyxy[0][0]), int(box.xyxy[0][1]), int(box.xyxy[0][2]), int(box.xyxy[0][3]))
      # print(f'box_bounds: {box_bounds}')

      # record bounding box bounds for deepSORT
      xmin, ymin, xmax, ymax = int(box.xyxy[0][0]), int(box.xyxy[0][1]), int(box.xyxy[0][2]), int(box.xyxy[0][3])
      if box.id is not None:              # <-- make sure box.id still works without yolo_model.track()
        class_id = int(box.id)
      else:
        class_id = 0

      # deepSORT update_tracks expects [x, y, width, height]
      DS_results.append([[xmin, ymin, xmax - xmin, ymax - ymin], conf, class_id])

