# some documentation here: https://github.com/google-ai-edge/mediapipe/blob/master/docs/solutions/pose.md

def skeletonize_crop(mp_modules, img_bg_clean, crop_jpg, box_bounds, predicted_label,
                     pose_detection_conf, pose_model_complexity):
  """
  skeletonization function. Takes a crop image with a person in it, runs pose detection,
  then draws the pose onto the clean background image.

  :param img_bg_clean:      clean background image to draw pose skeleton into
  :param crop_jpg:          crop image containing person
  :param box_bounds:        bounds to crop out of clean background
  :param predicted_label:   determines the color of the pose skeleton

  :return:             skeletonized crop image
  """

  # unpack mediapipe pose modules
  mp_drawing, mp_drawing_styles, mp_holistic, mp_pose, mp_face_mesh = mp_modules

  # save copy as PIL.Image for crop()
  pil_img_bg_clean = Image.fromarray(img_bg_clean)

  # draw pose onto crop               <-- instead of drawing pose into original crop. draw it onto background crop
  pose_input = np.array(crop_jpg)

  # crop desired box out of PIL.Image.Image
  clean_crop = pil_img_bg_clean.crop(box_bounds)

  # convert PIL.Image.Image to ndarray
  clean_crop = np.array(clean_crop)


  ####################################################
  # Skeletonization
  ####################################################

  # create pose skeleton
  with mp_pose.Pose(static_image_mode=True, min_detection_confidence=pose_detection_conf, model_complexity=pose_model_complexity) as pose:

    img_height, img_width, _ = pose_input.shape

    pose_results = pose.process(cv2.cvtColor(pose_input, cv2.COLOR_BGR2RGB))

    # determine draw color based on man(1)/woman(0)
    if predicted_label == 1:
      color = mp_drawing.DrawingSpec(color=(255, 0, 0), thickness=2)
    elif predicted_label == 0:
      color = mp_drawing.DrawingSpec(color=(0, 0, 255), thickness=2)

    # this line is for drawing pose back on original images   (person included)
    # mp_drawing.draw_landmarks(pose_img, pose_results.pose_landmarks, mp_pose.POSE_CONNECTIONS, connection_drawing_spec = color)

    # draws pose skeleton only on background crop
    mp_drawing.draw_landmarks(clean_crop, pose_results.pose_landmarks, mp_pose.POSE_CONNECTIONS, connection_drawing_spec = color)


    return clean_crop

