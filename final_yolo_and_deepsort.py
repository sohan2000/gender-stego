def create_param_combos(params_list):
  """
  a function that generates a list of all combinations of the input parameters.
  output is deterministic.

  each list element corresponds to a combination represented by a tuple in the format:

  (yolo_detection_conf, yolo_iou, yolo_augment, deepsort_maxage,
   deepsort_max_iou_distance, deepsort_n_init, deepsort_nms_max_overlap,
   deepsort_max_cosine_distance, pose_detection_conf, pose_model_complexity)

  :param params_list:      a list of lists. each list contains the intervals of the
                           parameters to be tested

  :return:                 a list of tuples. each tuple corresponds to a combination
                           of the input parameters
  """

  # create all combinations of list  <-- deterministic
  params_list = list(product(*params_list))

  # write combos to txt in drive. overwrite if it already exists
  txt_path = f'{OUTPUT_VIDEOS_FOLDER_PATH}/deepsort_param_combos.txt'
  with open(txt_path, 'w') as f:
    for combonum, combo in enumerate(params_list, 0):
      f.write(f'combo{combonum} \n')
      f.write(f'yolo_detection_conf: {combo[0]} \n')
      f.write(f'yolo_iou: {combo[1]} \n')
      f.write(f'yolo_augment: {combo[2]} \n')
      f.write(f'deepsort_maxage: {combo[3]} \n')
      f.write(f'deepsort_max_iou_distance: {combo[4]} \n')
      f.write(f'deepsort_n_init: {combo[5]} \n')
      f.write(f'deepsort_nms_max_overlap: {combo[6]} \n')
      f.write(f'deepsort_max_cosine_distance: {combo[7]} \n')
      f.write(f'pose_detection_conf: {combo[8]} \n')
      f.write(f'pose_model_complexity: {combo[9]} \n')
      f.write('\n')


  return params_list

