from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score
from sklearn.metrics import mean_absolute_error, mean_squared_error

def compute_metrics(actual, detected):
  """
  function that actually generates the metrics
  currently generates: mae, mse, accuracy, precision, recall, f1

  :param actual:       actual number of people in frame
  :param detected:     detected number of people in frame

  :return:             a tuple containing all metrics
  """

  # print(type(actual), type(detected))

  # compute regression metrics
  mae = mean_absolute_error(actual, detected)
  mse = mean_squared_error(actual, detected)


  # Convert to binary labels for classification metrics (1 if match, 0 if mismatch)
  actual_binary = [1 if a == d else 0 for a, d in zip(actual, detected)]
  detected_binary = [1] * len(actual)

  # compute classification metrics
  accuracy = accuracy_score(actual_binary, detected_binary)
  precision = precision_score(actual_binary, detected_binary, zero_division=0)
  recall = recall_score(actual_binary, detected_binary, zero_division=0)
  f1 = f1_score(actual_binary, detected_binary, zero_division=0)


  return (accuracy, precision, recall, f1, mae, mse)




